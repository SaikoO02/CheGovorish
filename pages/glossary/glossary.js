function groupByLetter(items) {
  const groups = new Map();
  items.forEach((t) => {
    const raw = (t.word || "").trim();
    const letter = raw ? raw[0].toUpperCase() : "#";
    if (!groups.has(letter)) groups.set(letter, []);
    groups.get(letter).push(t);
  });
  return Array.from(groups.entries()).sort(([a], [b]) => a.localeCompare(b, "ru"));
}

function renderList(items) {
  const list = document.getElementById("glossary-list");
  if (!list) return;

  const grouped = groupByLetter(items);

  list.innerHTML = grouped
    .map(([letter, terms]) => {
      const cards = terms
        .map(
          (t) => `
            <article class="term">
              <h2 class="term__word">${t.word}</h2>
              ${t.en ? `<div class="term__en">[${t.en}]</div>` : ""}
              ${t.tag ? `<div class="term__tag">${t.tag}</div>` : ""}
              <p class="term__def">${t.def}</p>
              <button class="term__footer" type="button" aria-expanded="false">
                <img class="term__icon" src="image/ICONS_Glossary.png" width="20" height="20" alt="" aria-hidden="true">
                <span class="term__expand">Развернуть</span>
              </button>
              <div class="term__expanded">
                ${t.ru ? `<div class="term__expanded-section">
                  <div class="term__expanded-heading">
                    <img class="term__expanded-icon-lang" src="image/ICONS_Russia.svg" width="26" height="26" alt="" aria-hidden="true">
                    <span class="term__expanded-label">Русский:</span>
                  </div>
                  <p class="term__expanded-ru">${t.ru}</p>
                </div>` : ""}
                ${t.example ? `<div class="term__expanded-section">
                  <div class="term__expanded-heading">
                    <img class="term__expanded-icon-chat" src="image/ICONS_Dialogue.svg" width="22" height="22" alt="" aria-hidden="true">
                    <span class="term__expanded-label">Пример использования:</span>
                  </div>
                  <div class="term__expanded-dialogue">
                    ${t.example.map(([s, text]) => `<p><strong>${s}:</strong> — ${text}</p>`).join("")}
                  </div>
                </div>` : ""}
              </div>
            </article>
          `
        )
        .join("");

      return `
        <section class="glossary-group" aria-label="Буква ${letter}">
          <div class="glossary-group__letter">${letter}</div>
          <div class="glossary-group__terms">${cards}</div>
        </section>
      `;
    })
    .join("");
}

document.addEventListener("DOMContentLoaded", () => {
  renderList(TERMS);

  const list = document.getElementById("glossary-list");
  if (list) {
    list.addEventListener("click", (e) => {
      const btn = e.target.closest(".term__footer");
      if (!btn) return;
      const article = btn.closest(".term");
      const expanded = article.querySelector(".term__expanded");
      const label = btn.querySelector(".term__expand");
      if (!expanded) return;
      const isOpen = expanded.classList.contains("term__expanded--open");
      if (isOpen) {
        expanded.classList.remove("term__expanded--open");
        btn.setAttribute("aria-expanded", "false");
        if (label) label.textContent = "Развернуть";
      } else {
        expanded.classList.add("term__expanded--open");
        btn.setAttribute("aria-expanded", "true");
        if (label) label.textContent = "Свернуть";
      }
    });
  }

  const input = document.getElementById("glossary-search");
  if (!input) return;

  input.addEventListener("input", () => {
    const q = input.value.trim().toLowerCase();
    if (!q) return renderList(TERMS);
    renderList(
      TERMS.filter((t) => `${t.word} ${t.tag} ${t.def}`.toLowerCase().includes(q))
    );
  });
});

