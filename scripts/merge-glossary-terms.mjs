const incoming = parsePairs(INPUT);
const added = [];
for (const t of incoming) {
  if (!existingKeys.has(normKey(t.word))) {
    existing.push({ word: t.word, tag: "", def: t.def });
    existingKeys.add(normKey(t.word));
    added.push(t.word);
  }
}

existing.sort((a, b) => a.word.localeCompare(b.word, "ru", { sensitivity: "base" }));

const header = glossarySrc.slice(0, glossarySrc.indexOf("const TERMS"));
const footer = glossarySrc.slice(glossarySrc.indexOf("];") + 2);

const formatted = formatTerms(existing);
fs.writeFileSync(glossaryPath, header + formatted + footer, "utf8");

console.log(`Existing: ${existing.length - added.length}, added: ${added.length}, total: ${existing.length}`);
console.log("Added terms:", added.join(", "));

function formatTerms(terms) {
  const lines = ["const TERMS = ["];
  for (const t of terms) {
    const word = JSON.stringify(t.word);
    const tag = JSON.stringify(t.tag);
    const def = JSON.stringify(t.def);
    lines.push("  {");
    lines.push(`    word: ${word},`);
    lines.push(`    tag: ${tag},`);
    lines.push(`    def: ${def},`);
    lines.push("  },");
  }
  lines[lines.length - 1] = "  },".replace("},", "}");
  lines.push("];");
  lines.push("");
  return lines.join("\n");
}
