function parsePairs(text) {
  const lines = text.split("\n").map((l) => l.trim()).filter(Boolean);
  const pairs = [];
  for (let i = 0; i < lines.length; i += 2) {
    if (i + 1 >= lines.length) break;
    pairs.push({ word: lines[i], def: lines[i + 1] });
  }
  return pairs;
}

function normKey(word) {
  return word
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/\s+/g, " ")
    .replace(/[«»""]/g, "")
    .trim();
}

